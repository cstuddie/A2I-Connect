// For unsupported languages, fall back to English. For supported languages, fall back per-key to English.
const SUPPORTED = Object.keys(translations);
const handler = {
  get(target, lang) {
    const langObj = target[SUPPORTED.includes(lang) ? lang : 'en'];
    if (langObj === target.en) return langObj;
    return new Proxy(langObj, {
      get(obj, key) {
        return key in obj ? obj[key] : target.en[key];
      }
    });
  }
};

export default new Proxy(translations, handler);
